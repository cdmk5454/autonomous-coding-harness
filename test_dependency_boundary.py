"""Bounded dependency-boundary regression for the release canary.

Classification under test:
  * REGENERABLE_DEPENDENCY (node_modules) — excluded from custody inventory
    and isolated copies; regenerable from the custodied package manifest and
    lockfile. Churn inside it (metadata or regenerated bytes) never reaches
    custody decisions.
  * METADATA_ONLY directory drift — a directory whose OS identity fields
    (mtime/size) drift while its entry-name set is stable is tolerated;
    entry-set changes remain fail-closed. Per-file custody checks are the
    content authority and are unchanged.
"""
import os
import sys
import unittest
from pathlib import Path
from unittest.mock import patch

import production_isolation
from production_isolation import inventory, copy_workspace_tree, REGENERABLE_DEPENDENCY_DIRS
from qa_quarantine import CandidateError

ORIGINAL_IDENTITY = production_isolation._file_identity


def fixture(root):
    root.mkdir(parents=True, exist_ok=True)
    (root / 'package.json').write_text('{"name":"rs","dependencies":{"highlight.js":"11"}}\n', encoding='utf-8')
    (root / 'package-lock.json').write_text('{}\n', encoding='utf-8')
    locale = root / 'src' / 'locale'
    locale.mkdir(parents=True)
    (locale / 'ko.json').write_text('{"label":{"test":"테스트입니다."}}\n', encoding='utf-8')
    (locale / 'en.json').write_text('{"label":{"test":"This is Test."}}\n', encoding='utf-8')
    deps = root / 'node_modules' / 'highlight.js' / 'lib' / 'languages'
    deps.mkdir(parents=True)
    (deps / 'core.js').write_text('export default null;\n', encoding='utf-8')
    return locale, deps


class DependencyBoundaryTests(unittest.TestCase):
    def setUp(self):
        import tempfile
        self.tmp = tempfile.TemporaryDirectory(prefix='dep-boundary-')
        self.root = Path(self.tmp.name)
        self.locale, self.deps = fixture(self.root)

    def tearDown(self):
        self.tmp.cleanup()

    def test_dependency_subtrees_are_not_custodied_or_copied(self):
        result = inventory(self.root, include_git=True)
        self.assertIn('package.json', result)
        self.assertIn('package-lock.json', result)
        self.assertIn('src/locale/ko.json', result)
        self.assertIn('src/locale/en.json', result)
        self.assertFalse([rel for rel in result if rel.startswith('node_modules/')])
        dest = self.root.parent / (self.root.name + '-candidate')
        copy_workspace_tree(self.root, dest)
        self.assertTrue((dest / 'src/locale/ko.json').is_file())
        self.assertTrue((dest / 'package.json').is_file())
        self.assertFalse((dest / 'node_modules').exists())
        self.assertEqual(inventory(dest, include_git=True), result)
        import shutil
        shutil.rmtree(dest)

    def test_dependency_metadata_churn_is_tolerated(self):
        # Identity drift (mtime/size oscillation) on a directory with a stable
        # entry-name set must not invalidate the inventory.
        target = self.locale.resolve()

        def drifting_identity(st):
            base = ORIGINAL_IDENTITY(st)
            if st.st_ino == target.lstat().st_ino:
                calls = drifting_identity.calls = getattr(drifting_identity, 'calls', 0) + 1
                if calls % 2:
                    return (base[0], base[1], 40960 if base[2] == 0 else 0) + base[3:]
            return base
        with patch.object(production_isolation, '_file_identity', side_effect=drifting_identity):
            result = inventory(self.root, include_git=True)
        self.assertIn('src/locale/ko.json', result)

    def test_dependency_entry_set_change_fails_closed(self):
        # A directory whose entries change across the listing window is a real
        # mutation and must fail closed.
        target = self.locale.resolve()

        def drifting(st):
            base = ORIGINAL_IDENTITY(st)
            if st.st_ino == target.lstat().st_ino:
                calls = drifting.calls = getattr(drifting, 'calls', 0) + 1
                if calls % 2:
                    return (base[0], base[1], 40960 if base[2] == 0 else 0) + base[3:]
            return base
        real_listdir = os.listdir
        with patch.object(production_isolation, '_file_identity', side_effect=drifting), \
             patch('os.listdir', side_effect=lambda p: sorted(real_listdir(p)) + ['phantom.tmp']):
            with self.assertRaises(CandidateError) as caught:
                inventory(self.root, include_git=True)
        self.assertEqual('CANDIDATE_DIRECTORY_CHANGED_DURING_INVENTORY', caught.exception.code)

    def test_regenerated_dependency_file_churn_never_reaches_custody(self):
        before = inventory(self.root, include_git=True)
        (self.deps / 'core.js').write_text('export default 1;\n', encoding='utf-8')
        (self.deps / 'extra.js').write_text('export default 2;\n', encoding='utf-8')
        os.utime(self.deps, None)
        after = inventory(self.root, include_git=True)
        self.assertEqual(before, after)

    def test_candidate_materialization_is_exact_and_deterministic(self):
        first = inventory(self.root, include_git=True)
        second = inventory(self.root, include_git=True)
        self.assertEqual(first, second)
        dest = self.root.parent / (self.root.name + '-c1')
        copy_workspace_tree(self.root, dest)
        dest2 = self.root.parent / (self.root.name + '-c2')
        copy_workspace_tree(self.root, dest2)
        self.assertEqual(inventory(dest, include_git=True), first)
        self.assertEqual(inventory(dest2, include_git=True), first)
        import shutil
        shutil.rmtree(dest)
        shutil.rmtree(dest2)

    def test_canary_build_runs_in_candidate_without_dependencies(self):
        import subprocess
        dest = self.root.parent / (self.root.name + '-build')
        copy_workspace_tree(self.root, dest)
        try:
            script = ("const f=require('fs');JSON.parse(f.readFileSync('src/locale/ko.json','utf8'));"
                      "JSON.parse(f.readFileSync('src/locale/en.json','utf8'))")
            result = subprocess.run([os.environ.get('RS_NODE', 'node'), '-e', script],
                cwd=dest, capture_output=True, timeout=60)
            self.assertEqual(0, result.returncode, result.stderr.decode('utf-8', 'replace'))
        finally:
            import shutil
            shutil.rmtree(dest)

    def test_profiled_custody_still_covers_declared_files_inside_dependencies(self):
        # Profiled inventories keep traversing dependency trees: tracked and
        # protected files under node_modules keep exact custody while
        # undeclared generated payloads stay unhashed (same contract as any
        # generated directory).
        from types import SimpleNamespace
        profile = SimpleNamespace(
            modules=[SimpleNamespace(name='app', path='.')],
            is_local_dev_config=lambda rel: Path(rel).name == '.env',
            is_protected_path=lambda rel: rel.endswith('/protected.py'),
            is_non_source_artifact=lambda rel: False)
        (self.deps / 'protected.py').write_text('frozen', encoding='utf-8')
        (self.root / 'node_modules' / 'tracked.py').write_text('tracked\n', encoding='utf-8')
        with patch.object(production_isolation, 'tracked_paths',
                          return_value={'node_modules/tracked.py'}):
            result = inventory(self.root, profile=profile)
        self.assertIn('node_modules/tracked.py', result)
        self.assertIn('node_modules/highlight.js/lib/languages/protected.py', result)
        self.assertNotIn('node_modules/highlight.js/lib/languages/core.js', result)
        before = dict(result)
        (self.deps / 'protected.py').write_text('drifted', encoding='utf-8')
        with patch.object(production_isolation, 'tracked_paths',
                          return_value={'node_modules/tracked.py'}):
            self.assertNotEqual(before, inventory(self.root, profile=profile))
        (self.deps / 'protected.py').unlink()

    def test_managed_source_mutation_remains_fail_closed(self):
        before = inventory(self.root, include_git=True)
        # authoritative locale byte change
        current = (self.locale / 'en.json').read_text(encoding='utf-8')
        (self.locale / 'en.json').write_text(current.replace('Test.', 'Mutated.'), encoding='utf-8')
        self.assertNotEqual(before, inventory(self.root, include_git=True))
        (self.locale / 'en.json').write_text(current, encoding='utf-8')
        self.assertEqual(before, inventory(self.root, include_git=True))
        # rename
        (self.locale / 'ko.json').rename(self.locale / 'ko2.json')
        self.assertNotEqual(before, inventory(self.root, include_git=True))
        (self.locale / 'ko2.json').rename(self.locale / 'ko.json')
        # delete
        (self.locale / 'ko.json').unlink()
        self.assertNotEqual(before, inventory(self.root, include_git=True))
        (self.locale / 'ko.json').write_text('{"label":{"test":"테스트입니다."}}\n', encoding='utf-8')

    def test_package_manifest_and_lockfile_mutation_remains_fail_closed(self):
        before = inventory(self.root, include_git=True)
        original = (self.root / 'package.json').read_text(encoding='utf-8')
        (self.root / 'package.json').write_text(original.replace('highlight.js', 'left-pad'), encoding='utf-8')
        self.assertNotEqual(before, inventory(self.root, include_git=True))
        (self.root / 'package.json').write_text(original, encoding='utf-8')
        lock = (self.root / 'package-lock.json').read_text(encoding='utf-8')
        (self.root / 'package-lock.json').write_text('{"locked":true}\n', encoding='utf-8')
        self.assertNotEqual(before, inventory(self.root, include_git=True))
        (self.root / 'package-lock.json').write_text(lock, encoding='utf-8')

    def test_managed_byte_change_during_copy_breaks_parity(self):
        before = inventory(self.root, include_git=True)
        dest = self.root.parent / (self.root.name + '-raced')
        # Simulate a managed byte change after the pre-copy inventory: the
        # post-copy parity comparison (the caller's contract) must see it.
        current = (self.locale / 'ko.json').read_text(encoding='utf-8')
        (self.locale / 'ko.json').write_text(current.replace('테스트입니다.', '경쟁.'), encoding='utf-8')
        try:
            copy_workspace_tree(self.root, dest)
            self.assertNotEqual(before, inventory(dest, include_git=True))
        finally:
            (self.locale / 'ko.json').write_text(current, encoding='utf-8')
            import shutil
            shutil.rmtree(dest, ignore_errors=True)


if __name__ == '__main__':
    unittest.main(verbosity=2)
