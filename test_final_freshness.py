"""Disposable multi-module custody regressions; no live control or Product state."""
import fnmatch
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

from isolated_promotion import IsolatedCanonicalPromotion, module_heads
import production_isolation
from production_isolation import inventory, normalized_preserved_inventory
from qa_quarantine import CandidateError
from task_state import TaskState


class FreshnessTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='final-freshness-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.canonical = self.root/'canonical'
        self.canonical.mkdir()
        self.profile = SimpleNamespace(
            modules=[SimpleNamespace(name=name, path=name) for name in ('web', 'server')],
            is_local_dev_config=lambda rel: Path(rel).name == '.env',
            is_protected_path=lambda rel: rel.endswith('/protected.py'),
            is_non_source_artifact=lambda rel: fnmatch.fnmatchcase(rel, '*/report.md'))
        for name in ('web', 'server'):
            repo = self.canonical/name
            repo.mkdir()
            for rel in ('src.py', 'test.py', 'node_modules/tracked.py'):
                target = repo/rel
                target.parent.mkdir(exist_ok=True)
                target.write_bytes(b'original\n')
            self.git(repo, 'init', '-q')
            self.git(repo, 'config', 'core.autocrlf', 'false')
            self.git(repo, 'add', '.')
            self.git(repo, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid',
                     '-c', 'commit.gpgsign=false', 'commit', '-qm', 'fixture')
            for index in range(32):
                (repo/'node_modules'/f'payload-{index}.bin').write_bytes(b'x'*65536)
            (repo/'node_modules/.env').write_bytes(b'fixture-only')
            (repo/'node_modules/protected.py').write_bytes(b'frozen')
        self.source = self.root/'source'
        self.candidate = self.root/'candidate'
        shutil.copytree(self.canonical, self.source)
        shutil.copytree(self.canonical, self.candidate)
        self.service = SimpleNamespace(working_dir=self.candidate,
            _load_profile=lambda: (self.profile, None), task_root=self.root/'tasks')
        self.job = {'job_id': 'FRESH', 'request': {'target_resources': ['web/src.py'],
            'test_plan': {'required_tests': ['web/test.py']}},
            'last_result': {'changed_files': ['web/src.py']}}
        self.promoter = IsolatedCanonicalPromotion(self.canonical, self.root/'publication', None)
        self.promoter.register(self.job, self.service, self.source)
        self.promoter.allocations.clear()

    @staticmethod
    def git(repo, *args):
        return subprocess.run(['git', '-C', str(repo), *args], check=True,
                              capture_output=True).stdout.decode().strip()

    def reopen(self, **kwargs):
        self.promoter.register_preserved(self.job, self.service, self.source, **kwargs)

    def test_preserved_registration_and_task_do_not_read_generated_payloads(self):
        original = production_isolation._hash_inventory_file
        reads = []
        def counted(path, expected):
            reads.append(Path(path))
            return original(path, expected)
        for root in (self.source, self.canonical, self.candidate):
            (root/'web/node_modules/payload-0.bin').write_bytes(b'new generated bytes')
        with patch.object(production_isolation, '_hash_inventory_file', counted):
            self.reopen()
            # Stop after the real source freshness check, before task authority.
            with patch.object(TaskState, 'load', side_effect=RuntimeError('freshness-passed')):
                with self.assertRaisesRegex(RuntimeError, 'freshness-passed'):
                    self.promoter._task(self.job, self.service, {'task_id': 'unused'})
        self.assertFalse([p for p in reads if p.name.startswith('payload-')])
        self.assertTrue(any(p.name == 'tracked.py' for p in reads))
        self.assertTrue(any(p.name == '.env' for p in reads))

    def test_source_test_config_protected_tracked_and_undeclared_drift_block(self):
        for rel in ('web/src.py', 'server/test.py', 'web/node_modules/.env',
                    'server/node_modules/protected.py', 'web/node_modules/tracked.py',
                    'server/undeclared.py'):
            with self.subTest(rel=rel):
                target = self.source/rel
                previous = target.read_bytes() if target.exists() else None
                target.write_bytes(b'drift')
                with self.assertRaisesRegex(CandidateError, 'CANDIDATE_BASE_MISMATCH'):
                    self.reopen()
                if previous is None:
                    target.unlink()
                else:
                    target.write_bytes(previous)

    def test_canonical_same_bytes_head_and_branch_drift_block(self):
        repo = self.canonical/'server'
        original = self.git(repo, 'rev-parse', 'HEAD')
        self.git(repo, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid',
                 '-c', 'commit.gpgsign=false', 'commit', '--allow-empty', '-qm', 'new head')
        with self.assertRaisesRegex(CandidateError, 'CANDIDATE_BASE_STALE'):
            self.reopen()
        self.git(repo, 'reset', '--soft', original)
        self.git(repo, 'checkout', '-qb', 'other-branch')
        with self.assertRaisesRegex(CandidateError, 'CANDIDATE_BASE_STALE'):
            self.reopen()

    def test_source_head_drift_and_post_registration_head_drift_block(self):
        self.reopen()
        self.git(self.source/'web', 'checkout', '-qb', 'other-branch')
        with patch.object(TaskState, 'load', side_effect=AssertionError('must not load')):
            with self.assertRaisesRegex(CandidateError, 'CANDIDATE_OWNERSHIP_MISMATCH'):
                self.promoter._task(self.job, self.service, {'task_id': 'unused'})
        self.promoter.allocations.clear()
        with self.assertRaisesRegex(CandidateError, 'CANDIDATE_BASE_MISMATCH'):
            self.reopen()

    def test_authorized_refresh_separates_source_and_canonical_heads(self):
        repo = self.canonical/'server'
        (repo/'pulled.py').write_bytes(b'authorized separate change')
        self.git(repo, 'add', 'pulled.py')
        self.git(repo, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid',
                 '-c', 'commit.gpgsign=false', 'commit', '-qm', 'authorized fixture')
        self.reopen(authorized_head_refresh=True)
        allocation = self.promoter.allocations['FRESH']
        self.assertNotEqual(allocation['source_heads'], allocation['canonical_heads'])
        self.assertEqual(module_heads(self.canonical, self.profile), allocation['canonical_heads'])
        self.assertEqual(module_heads(self.source, self.profile), allocation['source_heads'])

    def test_detached_unborn_and_effective_worktree_identity(self):
        attached = module_heads(self.source, self.profile)
        self.git(self.source/'web', 'checkout', '--detach')
        detached = module_heads(self.source, self.profile)
        self.assertEqual(attached['web']['head'], detached['web']['head'])
        self.assertNotEqual(attached['web']['branch'], detached['web']['branch'])
        unborn = self.source/'empty'
        unborn.mkdir()
        self.git(unborn, 'init', '-q')
        self.profile.modules.append(SimpleNamespace(name='empty', path='empty'))
        self.assertEqual('', module_heads(self.source, self.profile)['empty']['head'])
        self.git(self.source/'web', 'config', 'core.worktree', str(self.canonical/'web'))
        with self.assertRaisesRegex(CandidateError, 'CANDIDATE_GIT_OWNERSHIP_INVALID'):
            module_heads(self.source, self.profile)

    def test_generated_hardlink_and_junction_are_rejected(self):
        link = self.source/'web/node_modules/hard.py'
        os.link(self.source/'web/src.py', link)
        with self.assertRaisesRegex(CandidateError, 'CANDIDATE_HARDLINK_DENIED'):
            inventory(self.source, profile=self.profile)
        link.unlink()
        metadata_link = self.source/'web/.git/hard-payload'
        external = self.root/'outside-payload'
        external.write_bytes(b'outside custody')
        os.link(external, metadata_link)
        with self.assertRaisesRegex(CandidateError, 'CANDIDATE_HARDLINK_DENIED'):
            inventory(self.source, profile=self.profile)
        metadata_link.unlink()
        link = self.source/'web/node_modules/link'
        if os.name == 'nt':
            subprocess.run(['cmd', '/c', 'mklink', '/J', str(link), str(self.candidate/'web')],
                           check=True, capture_output=True)
        else:
            link.symlink_to(self.candidate/'web', target_is_directory=True)
        try:
            with self.assertRaisesRegex(CandidateError, 'CANDIDATE_LINK_DENIED'):
                inventory(self.source, profile=self.profile)
        finally:
            if os.name == 'nt':
                link.rmdir()
            else:
                link.unlink()

    def test_monorepo_tracked_generated_file_and_preserved_non_source(self):
        self.git(self.source, 'init', '-q')
        module = self.source/'lib'
        (module/'target').mkdir(parents=True)
        (module/'target/source.py').write_bytes(b'tracked')
        self.git(self.source, 'add', 'lib/target/source.py')
        self.profile.modules.append(SimpleNamespace(name='lib', path='lib'))
        (self.source/'web/report.md').write_bytes(b'known non-source')
        result = inventory(self.source, profile=self.profile)
        self.assertIn('lib/target/source.py', result)
        self.assertNotIn('web/report.md', result)
        recorded = {**result, 'web/report.md': 'old-report'}
        self.assertEqual(result, normalized_preserved_inventory(
            self.source, recorded, profile=self.profile))
        self.assertIn('web/report.md', inventory(self.source, profile=self.profile,
                                                preserve=['web/report.md']))


if __name__ == '__main__':
    unittest.main()
